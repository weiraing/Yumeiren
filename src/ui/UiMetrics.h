// 页面级尺寸的单一出处。
//
// 为什么值得单独放一个头文件：动态壁纸页与看板娘页是**同一种左右布局** ——
// 左边一张固定宽的控制卡，右边 `addWidget(..., 1)` 吃掉剩余宽度。两边的左列
// 宽度必须一致，否则切页时左卡会横向「跳一下」。以前这个 250 在两个 .cpp 里
// 各写了一遍，改一处忘另一处就会漂，所以收到这里。
//
// 调大左列 = 从右列匀宽度过来，**窗口总宽不变**；窗口被拉宽时多出来的空间
// 仍然全给右列(左列是固定宽，不参与拉伸)。
#ifndef UIMETRICS_H
#define UIMETRICS_H

namespace uimetrics {

// 左右布局页面的左列宽度（逻辑像素）。
// 原值 250：左卡里的按钮文字与提示语偏挤，右列(模型/参数、播放列表)反而偏空，
// 2026-09-17 按用户要求调到 300 —— 右列同步收窄 50，总宽不动。
inline constexpr int kPageLeftColWidth = 300;

} // namespace uimetrics

#endif // UIMETRICS_H

// 页面级尺寸的单一出处。
//
// 动态壁纸页与看板娘页是同一种左右布局：左边固定宽的控制卡，右边 addWidget(..., 1)
// 吃掉剩余宽度。两列宽度集中在一处，切页时左卡才不会横向跳。
#ifndef UIMETRICS_H
#define UIMETRICS_H

namespace uimetrics {

// 左右布局页面的左列宽度(逻辑像素)。调大它是从右列匀宽度过来，窗口总宽不变。
inline constexpr int kPageLeftColWidth = 300;

// 右列(媒体库/网格墙)能缩到的最小宽度(逻辑像素)。
//
// 为什么必须有这个下限：向右拉伸是自动的，向左收缩却不是 —— 只要右列里还有
// 按内容定宽的部件(库卡片工具栏三连按钮、两列表头、不折行的状态文字加起来约 316px)，
// 整个页面就会停在"左列 + 右列最小宽"上不再变窄。此时继续拖窗口右下角，
// 窗口边框跟着动、页面却纹丝不动，看起来就是"右侧栏缩不动、内容被边上盖住"。
// 给一个明确的 minWidth 后，窗口能一路缩到这个下限，两边同步收。
//
// 反向约束：这个值不能大于「窗口最小宽度 880 - 左列 300 - 左右边距 36 - 列间距 14」，
// 否则窄窗口里反而撑出竖向滚动条。48px 只是"别缩成负数"的兜底，不会真的用到。
inline constexpr int kPageRightColMinWidth = 48;

} // namespace uimetrics

#endif // UIMETRICS_H
